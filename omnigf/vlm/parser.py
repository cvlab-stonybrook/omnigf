"""Output parsing for VLM gaze predictions (JSON format)."""

import json
import re
import logging
from typing import Dict, List, Optional, Tuple

logger = logging.getLogger(__name__)


def person_anchor_token_variants(pid: int, prompt_mode: str) -> List[str]:
    """Return the candidate anchor strings used by the heatmap-decoder
    hidden-state extraction.

    Both the collator (training-time,
    ``omnigf/vlm/collator.py:_find_person_positions``) and the model
    (inference-time,
    ``omnigf/vlm/models_ge.py:_find_person_positions_in_generated``)
    encode each candidate via ``tokenizer.encode(s, add_special_tokens=False)``
    and search the input_ids for any of the resulting token-id sequences,
    using the rightmost (most-recent) match's *first* token index.

    Why a list instead of a single string
    -------------------------------------
    Subword tokenisers (BPE-style, including Qwen3-VL's) merge a leading
    space with the following word. So ``"Person 0"`` tokenises
    context-dependently:

      * Standalone or after a non-space (e.g. ``\\n``)        -> ``[10680, 220, 15]``
      * Mid-prose with a leading space (e.g. ``" ... and "``) -> ``[7357, 220, 15]``

    A single-string anchor would miss whichever variant we didn't
    encode. By returning *both* variants the caller's search recovers
    the correct in-context occurrence regardless of position-in-turn.

    Mappings:
      * ``"natural_language"`` -> ``["Person {pid}", " Person {pid}"]``.
        Both forms appear in real assistant turns: form (a) for
        ``pid=0`` at start-of-turn after ``\\n``, form (b) for
        ``pid>=1`` after ``". "``. The user prompt uses form (b)
        consistently (e.g. ``"are Person 0 ("``).
      * everything else -> ``["P{pid}:"]``. The JSON anchor's leading
        ``"P"`` is not space-fused by Qwen's BPE, so its tokenisation
        is context-invariant — one variant is enough.
    """
    return [f"P{pid}:"]


# Back-compat alias: old single-string API used by any external callers.
# Match a standalone ``{...}`` object that contains one of the social keys.
# Used for the ``point_then_social`` two-block and the pure social target
# formats. Non-greedy so it stops at the first closing brace pair that
# balances; good enough for the one-line social JSON we emit.
_SOCIAL_LINE_RE = re.compile(
    r"\{[^{}]*\"(?:LAH|LAEO|SA)\"[^{}]*\}",
    flags=re.DOTALL,
)


class MultiPersonOutputParser:
    """Parse sequential per-person gaze predictions from VLM text output.

    Expected JSON format (quantised, coord_bins=1000)::

        P0: {"status": "inside", "point_2d": [450, 620]}
        P1: {"status": "outside"}
        P2: {"status": "inside", "point_2d": [780, 340]}

    Each person line starts with ``P<id>:`` followed by a JSON object.
    Coordinates are integers in ``[0, coord_bins-1]`` and are normalised to
    ``[0, 1]`` before returning.
    """

    # Match P<id>: followed by a JSON object {...}
    _LINE_RE = re.compile(r"P(\d+)\s*:\s*(\{.*\})")

    def __init__(self, coord_bins: int = 1000):
        self.coord_bins = coord_bins

    def parse(self, text: str, context: Optional[str] = None) -> List[Dict]:
        """Parse multi-person VLM output text.

        Supports both single-block output (one ``P<id>:`` line per person) and
        the two-block ``point_then_category`` format, where a point line and
        a category line share the same ``pid``. Lines with the same pid are
        merged into a single dict.

        Args:
            text: Raw text generated by the VLM.
            context: Optional context string (e.g. image path) prepended to
                warnings so users can identify which frame produced
                malformed output.

        Returns:
            List of dicts, each with keys:
                - ``pid`` (int): person ID
                - ``inside`` (bool, optional): True if gaze target is inside.
                  Omitted for entries parsed from a category-only line with
                  no matching point line.
                - ``x`` (float, optional): normalised gaze x (only when inside)
                - ``y`` (float, optional): normalised gaze y (only when inside)
                - ``category`` (str, optional): predicted object category
        """
        ctx_prefix = f"[{context}] " if context else ""
        raw_entries: List[Dict] = []
        for line in text.strip().split("\n"):
            line = line.strip()
            m = self._LINE_RE.search(line)
            if m is None:
                continue
            pid = int(m.group(1))
            try:
                obj = json.loads(m.group(2))
            except json.JSONDecodeError:
                logger.warning("%sMalformed JSON in line: %s", ctx_prefix, line)
                continue

            if "status" not in obj:
                # Category-only line (two-block "point_then_category" format)
                if "category" in obj:
                    raw_entries.append({"pid": pid, "category": str(obj["category"])})
                continue
            status = obj["status"].lower()
            if status == "outside":
                raw_entries.append({"pid": pid, "inside": False})
            elif status == "inside":
                pt = obj.get("point_2d")
                if (
                    pt is not None
                    and isinstance(pt, (list, tuple))
                    and len(pt) >= 2
                    and isinstance(pt[0], (int, float))
                    and isinstance(pt[1], (int, float))
                ):
                    x = float(pt[0]) / (self.coord_bins - 1)
                    y = float(pt[1]) / (self.coord_bins - 1)
                    entry = {"pid": pid, "inside": True, "x": x, "y": y}
                    cat = obj.get("category")
                    if cat is not None:
                        entry["category"] = str(cat)
                    raw_entries.append(entry)
                else:
                    logger.warning("%sINSIDE without valid point_2d: %s", ctx_prefix, line)
            else:
                logger.warning("%sUnknown status %r in line: %s", ctx_prefix, status, line)

        # Merge entries that share a pid (point line + category line).
        merged: Dict[int, Dict] = {}
        for entry in raw_entries:
            pid = entry["pid"]
            if pid in merged:
                merged[pid].update({k: v for k, v in entry.items() if k != "pid"})
            else:
                merged[pid] = entry
        return list(merged.values())
